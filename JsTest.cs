namespace Demo3D.Components {

    /// <summary>
    /// Test support (stage 4, task 2.14 — deliberately degraded).
    ///
    /// JScript has no NUnit equivalent, so this tool does NOT run tests. It does the two halves that
    /// can be done honestly:
    ///   action=list      every event handler function, which script declares it, and whether the
    ///                    visual its name targets exists in the scene (= is it reachable at all)
    ///   action=scaffold  a ready-to-mount self-check script (built-ins only, pure arithmetic, no
    ///                    Math.*, one print per check) plus the exact manual steps that remain
    ///
    /// Mounting a script on a visual is a manual UI step (README §8.2) and Reset/Play is a human
    /// decision, so both are handed off instead of faked.
    /// </summary>
    internal static class JsTestKernel {

        /// <summary>Event function name -> "<prefix>_On<Event>" split, or null when malformed.</summary>
        public static void Split(string functionName, out string prefix, out string eventName) {
            prefix = functionName;
            eventName = "";
            var cut = functionName.IndexOf("_On", StringComparison.Ordinal);
            if (cut <= 0 || cut + 3 >= functionName.Length) return;
            prefix = functionName.Substring(0, cut);
            eventName = functionName.Substring(cut + 3);
        }

        public static string Scaffold(string scriptName, string host, string eventName, int lines) {
            var sb = new StringBuilder();
            sb.Append("// " + scriptName + " - self-check scaffold generated by js_test (stage 4).\r\n");
            sb.Append("// Remaining MANUAL steps: (1) mount this script on the visual '" + host + "' in the UI\r\n");
            sb.Append("// (mounting cannot be automated, README §8.2); (2) press Reset and read the Console lines.\r\n");
            sb.Append("// Engine notes: no Math.* (use pure arithmetic), print() writes to the Message Log/Console.\r\n");
            sb.Append("\r\n");
            sb.Append("[Optimize(false)]\r\n");
            sb.Append("function " + host + "_On" + eventName + "( sender : Visual )\r\n");
            sb.Append("{\r\n");
            sb.Append("\tprint(\"" + scriptName + ": " + host + "_On" + eventName + " fired on \" + sender.Name);\r\n");
            sb.Append("\tprint(\"" + scriptName + ": model time = \" + doc.Time);\r\n");
            if (lines > 0) {
                sb.Append("\r\n");
                sb.Append("\t// pure arithmetic self-check (no Math.*: README §8.4)\r\n");
                sb.Append("\tvar targetPerHour = 1200;\r\n");
                sb.Append("\tvar secondsPerItem = 3600 / targetPerHour;\r\n");
                sb.Append("\tprint(\"" + scriptName + ": target \" + targetPerHour + \"/h -> \" + secondsPerItem + \" s/item\");\r\n");
                sb.Append("\tif (secondsPerItem <= 0) {\r\n");
                sb.Append("\t\tprint(\"" + scriptName + ": FAIL - secondsPerItem must be positive\");\r\n");
                sb.Append("\t\treturn;\r\n");
                sb.Append("\t}\r\n");
                sb.Append("\tprint(\"" + scriptName + ": FAIL - replace this scaffold with a real assertion\");\r\n");
            }
            sb.Append("}\r\n");
            return sb.ToString();
        }
    }

    public partial class JsScriptTools {

        [McpServerTool]
        [Description("Test support for JScript (no runner exists in this engine, so nothing is executed here). action=list maps every event handler function to its script and reports whether the visual its name targets exists in the scene (i.e. whether it can ever fire), grouped by prefix. action=scaffold writes a self-check script skeleton (built-ins only, pure arithmetic, no Math.*) and lists the manual steps that remain: mount it in the UI and press Reset.")]
        public string JsTest(
            [Description("list | scaffold")] string action = "list",
            [Description("list: script name filter (empty = every JScript); scaffold: the script to create or overwrite")] string target = "",
            [Description("scaffold: visual name used as the event prefix (default = the script name)")] string host = "",
            [Description("scaffold: event name, e.g. OnReset")] string @event = "OnReset",
            [Description("scaffold: write the script into the model instead of only returning it")] bool write = false,
            [Description("scaffold: after writing, press Reset once and confirm the script compiles")] bool verify = false) {
            if (string.Equals(action, "scaffold", StringComparison.OrdinalIgnoreCase)) {
                if (string.IsNullOrEmpty(target)) return "ERROR: 'target' (the script to create or overwrite) is required for action=scaffold.";
                var hostName = string.IsNullOrEmpty(host) ? target : host;
                // Accept both "OnReset" and "Reset": the handler name is built as <host>_On<event>,
                // so a caller passing the full event name produced Cylinder3_OnOnReset, which never
                // fires (measured 2026-10-01).
                var eventName = string.IsNullOrEmpty(@event) ? "Reset" : @event.Trim();
                if (eventName.StartsWith("On", StringComparison.OrdinalIgnoreCase)) eventName = eventName.Substring(2);
                if (eventName.Length == 0) eventName = "Reset";
                var source = JsTestKernel.Scaffold(target, hostName, eventName, 1);

                return ExecuteMcpCommand(McpPermission.AllowScriptRead, app => {
                    var doc = app.Document;
                    int visuals;
                    var scene = JsLintEngine.SceneNames(doc, out visuals);
                    var exists = JsScriptHelper.FindScript(doc, target) != null;

                    var sb = new StringBuilder();
                    sb.AppendLine("# JS TEST  action=scaffold  script=" + target + "  host=" + hostName + "  event=On" + eventName
                                + "  write=" + write);
                    if (scene.Contains(hostName)) sb.AppendLine("MOUNT '" + hostName + "' exists in the scene - after mounting this script the handler will fire on Reset.");
                    else sb.AppendLine("MOUNT '" + hostName + "' does NOT exist in the scene yet: the scaffold compiles, but its handler cannot fire"
                                     + " until a visual with that name exists and the script is mounted on it (README §8.2).");

                    string lintWarnings;
                    var lintErrors = JsLintBridge.Run(doc, target, source, out lintWarnings);
                    if (lintErrors.Length > 0) {
                        sb.AppendLine("ERROR: the generated scaffold fails lint (this is a bug in js_test, please report it):");
                        sb.Append(lintErrors);
                        return sb.ToString();
                    }
                    if (lintWarnings.Length > 0) sb.Append(lintWarnings);

                    if (!write) {
                        sb.AppendLine(exists ? "DRY-RUN: '" + target + "' exists and would be OVERWRITTEN. Re-run with write=true." 
                                             : "DRY-RUN: '" + target + "' would be CREATED. Re-run with write=true.");
                        sb.AppendLine("---- SCAFFOLD ----");
                        sb.Append(source);
                        return sb.ToString();
                    }

                    var err = JsScriptWrite.WriteScriptUnified(app, doc, target, source, true,
                                                              out var script, out var used, out var created);
                    if (err != null) return "ERROR: " + err;
                    var readback = JsScriptHelper.ReadSource(script) ?? "";
                    sb.AppendLine((created ? "Created" : "Wrote") + " '" + target + "' via " + used
                                + "  chars=" + readback.Length + "  rev=" + JsScriptHelper.Rev(readback));
                    sb.AppendLine(JsScriptWrite.Recompile(app, doc, script));
                    if (verify) {
                        string note;
                        var failure = JsCompileVerify.Run(app, target, out note);
                        sb.AppendLine(failure ?? ("Compile verify: " + note));
                    } else {
                        sb.AppendLine("Compile NOT verified: run with verify=true, or press Reset / reopen the model yourself.");
                    }
                    sb.AppendLine("Next manual steps: mount '" + target + "' on '" + hostName + "' in the UI, then press Reset and read the Console lines.");
                    JsDiagBuffer.Add("test", "info", target, "scaffold " + (created ? "created" : "written") + " rev=" + JsScriptHelper.Rev(readback));
                    return sb.ToString();
                });
            }

            if (!string.Equals(action, "list", StringComparison.OrdinalIgnoreCase)) {
                return "ERROR: unknown action '" + action + "'. Known: list | scaffold.";
            }

            return ExecuteMcpCommand(McpPermission.AllowScriptRead, app => {
                var doc = app.Document;
                int visuals;
                var scene = JsLintEngine.SceneNames(doc, out visuals);

                var sb = new StringBuilder();
                var scripts = 0;
                var functions = 0;
                var mounted = 0;
                var unmounted = 0;
                // prefix -> owning scripts (the actionable view for the manual mounting step)
                var byPrefix = new Dictionary<string, List<string>>(StringComparer.OrdinalIgnoreCase);
                var perScript = new List<string>();

                foreach (var s in JsScriptHelper.AllJScripts(doc)) {
                    var name = JsScriptHelper.NameOf(s);
                    if (!string.IsNullOrEmpty(target) && !string.Equals(name, target, StringComparison.OrdinalIgnoreCase)) continue;
                    scripts++;
                    var src = JsScriptHelper.ReadSource(s) ?? "";
                    var fns = JsScriptHelper.EventFunctions(src);
                    if (fns.Count == 0) {
                        perScript.Add("SCRIPT " + name + "  events=0");
                        continue;
                    }
                    var body = new StringBuilder();
                    var prefixes = new List<string>();
                    foreach (var fn in fns) {
                        string prefix, eventName;
                        JsTestKernel.Split(fn, out prefix, out eventName);
                        functions++;
                        var ok = scene.Contains(prefix);
                        if (ok) mounted++; else unmounted++;
                        if (!prefixes.Contains(prefix)) {
                            prefixes.Add(prefix);
                            if (!byPrefix.ContainsKey(prefix)) byPrefix[prefix] = new List<string>();
                            byPrefix[prefix].Add(name);
                        }
                        body.AppendLine("    " + (ok ? "OK   " : "NOMOUNT ") + fn
                                      + (ok ? "  (handler of visual '" + prefix + "')"
                                            : "  ('" + prefix + "' is not a visual of this scene)"));
                    }
                    perScript.Add("SCRIPT " + name + "  events=" + fns.Count + "  prefixes=[" + string.Join(", ", prefixes.ToArray()) + "]\n" + body.ToString().TrimEnd('\r', '\n'));
                }

                sb.AppendLine("# JS TEST  action=list  scripts=" + scripts + "  eventFunctions=" + functions
                            + "  prefixesInScene=" + mounted + "  prefixesNotInScene=" + unmounted + "  sceneVisuals=" + visuals);
                sb.AppendLine();
                sb.AppendLine("## by script");
                foreach (var line in perScript) sb.AppendLine(line);

                sb.AppendLine();
                sb.AppendLine("## by visual prefix (use this list for the manual mounting step)");
                var keys = new List<string>(byPrefix.Keys);
                keys.Sort(StringComparer.OrdinalIgnoreCase);
                foreach (var prefix in keys) {
                    var ok = scene.Contains(prefix);
                    sb.AppendLine((ok ? "OK       " : "NOMOUNT  ") + prefix + "  <- " + string.Join(", ", byPrefix[prefix].ToArray()));
                }
                sb.AppendLine();
                sb.AppendLine("NOTE no test runner is executed by this tool: mounting a script on a visual is a manual UI step and Reset/Play is a human decision (plan §5).");
                if (unmounted > 0) sb.AppendLine("NOTE " + unmounted + " handler(s) target visuals that do not exist in this scene - the scripts are likely copies from another model.");
                JsDiagBuffer.Add("test", "info", "", "list scripts=" + scripts + " events=" + functions + " notMounted=" + unmounted);
                return sb.ToString();
            });
        }
    }
}
